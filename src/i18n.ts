const dicts: Record<LangCode, Dict> = { en, zh };

function replaceAll(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), text);
}

/**
 * Translation lookup with {var} interpolation. Falls back to en, then the raw key.
 */
export function translate(lang: LangCode, key: string, vars?: Record<string, string | number>): string {
  const d = dicts[lang] ?? en;
  const raw = d[key] ?? en[key] ?? key;
  return replaceAll(raw, vars);
}

/**
 * React hook: returns a t() bound to the current app language. Re-renders on
 * language change because it subscribes to the settings slice.
 */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useApp((s) => s.settings.language) as LangCode;
  return (key, vars) => translate(lang, key, vars);
}